// catalog writes pkg/aws/zz_generated_instances.go from the AWS Price List:
// vCPU, memory, architecture, class and generation of every EC2 instance
// type (recommendations D2). It needs AWS credentials allowed
// pricing:GetProducts, the permission the tool already uses for prices.
//
//	go run ./hack/catalog
package main

import (
	"bytes"
	"context"
	"go/format"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"sort"
	"time"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/config"
	"github.com/aws/aws-sdk-go-v2/service/pricing"
	pricingtypes "github.com/aws/aws-sdk-go-v2/service/pricing/types"

	knvaws "github.com/staffops/kube-node-viewer/pkg/aws"
)

func main() {
	ctx := context.Background()
	cfg, err := config.LoadDefaultConfig(ctx, config.WithRegion("us-east-1"))
	if err != nil {
		log.Fatalf("loading AWS config: %s", err)
	}
	client := pricing.NewFromConfig(cfg)
	term := func(field, value string) pricingtypes.Filter {
		return pricingtypes.Filter{Field: aws.String(field), Type: pricingtypes.FilterTypeTermMatch, Value: aws.String(value)}
	}
	pages := pricing.NewGetProductsPaginator(client, &pricing.GetProductsInput{
		ServiceCode: aws.String("AmazonEC2"),
		Filters: []pricingtypes.Filter{
			term("regionCode", "us-east-1"),
			term("operatingSystem", "Linux"),
			term("preInstalledSw", "NA"),
			term("capacitystatus", "Used"),
			term("tenancy", "Shared"),
		},
		MaxResults: aws.Int32(100),
	})
	specs := map[string]knvaws.InstanceSpec{}
	for pages.HasMorePages() {
		out, err := pages.NextPage(ctx)
		if err != nil {
			log.Fatalf("GetProducts: %s", err)
		}
		for _, raw := range out.PriceList {
			var item struct {
				Product struct {
					Attributes knvaws.PriceListAttributes `json:"attributes"`
				} `json:"product"`
			}
			if err := json.Unmarshal([]byte(raw), &item); err != nil {
				continue
			}
			a := item.Product.Attributes
			if s, ok := a.Spec(); ok && a.InstanceType != "" {
				specs[a.InstanceType] = s
			}
		}
	}
	if len(specs) < 100 {
		log.Fatalf("only %d instance types read; refusing to write a partial table", len(specs))
	}
	names := make([]string, 0, len(specs))
	for n := range specs {
		names = append(names, n)
	}
	sort.Strings(names)

	var f bytes.Buffer
	fmt.Fprintf(&f, `/*
Licensed under the Apache License, Version 2.0 (the "License");
you may not use this file except in compliance with the License.
You may obtain a copy of the License at

    http://www.apache.org/licenses/LICENSE-2.0

Unless required by applicable law or agreed to in writing, software
distributed under the License is distributed on an "AS IS" BASIS,
WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
See the License for the specific language governing permissions and
limitations under the License.
*/

// Code generated by go run ./hack/catalog at %s from the AWS Price List; DO NOT EDIT.

package aws

var generatedInstanceSpecs = map[string]InstanceSpec{
`, time.Now().UTC().Format(time.RFC3339))
	for _, n := range names {
		s := specs[n]
		fmt.Fprintf(&f, "\t%q: {VCPU: %g, MemoryGiB: %g, Arch: %q, Class: %q, CurrentGeneration: %t},\n", n, s.VCPU, s.MemoryGiB, s.Arch, s.Class, s.CurrentGeneration)
	}
	fmt.Fprintln(&f, "}")
	src, err := format.Source(f.Bytes())
	if err != nil {
		log.Fatalf("formatting: %s", err)
	}
	if err := os.WriteFile("pkg/aws/zz_generated_instances.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d instance types", len(names))
}
