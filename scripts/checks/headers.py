"""Check provenance over the whole tree (AGENTS.md "Provenance and
licensing", rebrand R8 and design D5), not only the new files pre-commit sees.

    scripts/checks/headers.py    (verify.sh runs it; needs the import commit,
                                  so a clone with full history)

- Every tracked .go/.sh/.py file and git hook has the full Apache header
  (its LICENSE-2.0 line within the first 20 lines).
- Every file that came from upstream (same path in the import commit, a
  rename git detects, or MOVED below) and differs from its imported version
  carries the modification note right after the license block: in Go the
  first line after the block, with a blank line after it (so it is not the
  package doc); in a script the first comment line after the block; in a
  file without a license header within its first 5 lines. Files whose type
  has no rule must be listed in EXEMPT with the reason.
- LICENSE is the imported one and NOTICE keeps its first line.

KNV_IMPORT_COMMIT overrides the import commit (ADR-001, ADR-005); the
guardrail tests use it. Exit 1 on a problem, 2 when the import commit is
missing.
"""

import os
import re
import subprocess
import sys

IMPORT = os.environ.get("KNV_IMPORT_COMMIT", "f3aceaad51ef927264400d78c2a46cb3494faba6")
NOTE = "Modified by the kube-node-viewer authors"
URL = "http://www.apache.org/licenses/LICENSE-2.0"
LAST = "limitations under the License."

# upstream files moved and changed too much for git's rename detection
MOVED = {"cmd/kube-node-viewer/main.go": "cmd/eks-node-viewer/main.go"}

# changed upstream files without a note, and why
EXEMPT = {
    "README.md": "prose; it credits upstream, and NOTICE names this project",
    "CONTRIBUTING.md": "prose",
    "ATTRIBUTION.md": "generated by hack/gen_licenses.sh",
    "cmd/kube-node-viewer/ATTRIBUTION.md": "generated by hack/gen_licenses.sh",
    "go.mod": "tool-managed (go get, go mod tidy, Dependabot)",
    "go.sum": "tool-managed, no comment syntax",
    "NOTICE": "carries this project's own line (rebrand R8)",
}

HASH = re.compile(r"(^|/)(Makefile|CODEOWNERS|\.gitignore)$|\.(ya?ml|toml)$")


def git(*args, check=True):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=check).stdout


def kind(path):
    if path.endswith(".go"):
        return "go"
    if path.endswith((".sh", ".py")) or path.startswith(".githooks/"):
        return "script"
    if HASH.search(path):
        return "hash"
    if path.endswith(".tmpl"):
        return "tmpl"
    return None


def note_problem(path, lines):
    """None when the note is in place, else the rule it breaks."""
    k = kind(path)
    end = next((i for i, l in enumerate(lines[:25]) if LAST in l), None)
    if end is None:
        if k in ("hash", "tmpl"):
            ok = any(NOTE in l for l in lines[:5])
            return None if ok else "upstream file changed without the modification note in its first 5 lines"
        return "upstream file changed without the modification note"
    if not any(NOTE in l for l in lines):
        return "upstream file changed without the modification note"
    i = end + 1
    if k == "go":
        if i < len(lines) and lines[i].strip() == "*/":
            i += 1
        while i < len(lines) and not lines[i].strip():
            i += 1
        if i >= len(lines) or NOTE not in lines[i]:
            return "modification note not right after the license block"
        if i + 1 < len(lines) and lines[i + 1].strip():
            return "no blank line after the modification note (it would become the package doc)"
        return None
    while i < len(lines) and lines[i].strip() in ("#", ""):
        i += 1
    if i >= len(lines) or NOTE not in lines[i]:
        return "modification note not right after the license block"
    return None


def main():
    os.chdir(git("rev-parse", "--show-toplevel").strip() or ".")
    if subprocess.run(["git", "cat-file", "-e", IMPORT + "^{commit}"], capture_output=True).returncode:
        print(f"headers: the import commit {IMPORT} is not in this clone; "
              "fetch the full history (git fetch --unshallow)", file=sys.stderr)
        return 2
    problems = []
    tracked = [p for p in git("ls-files", "-z").split("\0") if p and os.path.isfile(p)]

    for p in tracked:
        if kind(p) not in ("go", "script"):
            continue
        with open(p, encoding="utf-8", errors="replace") as f:
            head = [next(f, "") for _ in range(20)]
        if not any(URL in l for l in head) or not any("Licensed under the Apache License" in l for l in head):
            problems.append((p, "no Apache license header"))

    imported = set(git("ls-tree", "-r", "-z", "--name-only", IMPORT).split("\0")) - {""}
    origin = {p: p for p in imported}
    for line in git("diff", "-M", "--name-status", "--diff-filter=R", IMPORT).splitlines():
        _, old, new = line.split("\t")
        origin[new] = old
    origin.update(MOVED)

    for p in tracked:
        old = origin.get(p)
        if old is None or p in EXEMPT:
            continue
        old_blob = git("rev-parse", "-q", "--verify", f"{IMPORT}:{old}", check=False).strip()
        if old_blob and old_blob == git("hash-object", p).strip():
            continue
        if kind(p) is None:
            problems.append((p, "upstream file changed, no rule for its type: add a note or an EXEMPT entry"))
            continue
        with open(p, encoding="utf-8", errors="replace") as f:
            rule = note_problem(p, f.read().split("\n"))
        if rule:
            problems.append((p, rule))

    if subprocess.run(["git", "diff", "--quiet", IMPORT, "--", "LICENSE"]).returncode:
        problems.append(("LICENSE", "LICENSE differs from the imported one"))
    first = git("show", f"{IMPORT}:NOTICE", check=False).split("\n", 1)[0]
    try:
        with open("NOTICE", encoding="utf-8") as f:
            now = f.readline().rstrip("\n")
    except OSError:
        now = None
    if now != first:
        problems.append(("NOTICE", "NOTICE first line changed"))

    if problems:
        print("headers: missing provenance", file=sys.stderr)
        for p, rule in problems:
            print(f"{p}\n  {rule}", file=sys.stderr)
        print(f"fix: copy the header of scripts/checks/headers.py (make boilerplate for Go); "
              f"put '{NOTE}, 2026.' as a comment right after the license block", file=sys.stderr)
        return 1
    print("headers: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
